test('история и отчёт ограничены датами, пропуски видны в PDF-представлении', async ({page}) => {
  await page.setViewportSize({width: 768, height: 900})
  await page.goto('./#/history')
  await page.getByRole('button', {name: 'День', exact: true}).click()
  await expect(page.getByRole('heading', {name: 'Гречка с курицей'})).toHaveCount(1)
  for (const duration of ['7 дней', '14 дней', '30 дней']) {
    await page.getByRole('button', {name: duration, exact: true}).click()
    await expect(page.getByRole('heading', {name: 'Гречка с курицей'})).toHaveCount(2)
  }
  await nav(page, 'Отчёт').click()
  await expect(page.getByRole('heading', {name: 'Отчёт', exact: true})).toBeVisible()
  await page.getByLabel('Дата начала').fill('2026-11-14')
  await page.getByLabel('Дата окончания').fill('2026-11-14')
  const report = page.getByRole('article', {name: 'Предпросмотр отчёта'})
  await expect(report).toContainText('14 ноября · 13:00 · Гречка с курицей')
  await expect(report).not.toContainText('Яблоко')
  await expect(report).not.toContainText('16 ноября')
  await expect(report.getByRole('cell', {name: 'Пробел CGM', exact: true})).toHaveCount(4)
  await expect(report.getByRole('row', {name: /14 ноября · 13:00 6,5 13:02/})).toBeVisible()
  await page.getByRole('button', {name: 'Сохранить отчёт'}).click()
  await expect(page.getByRole('heading', {name: 'Представление для печати'})).toBeVisible()
  await page.reload()
  await expect(report).toContainText('2026-11-14 — 2026-11-14')
  await page.emulateMedia({media: 'print'})
  await expect(page.getByRole('navigation')).toBeHidden()
  await expect(report).toContainText('Демо · синтетические данные')
  const pdf = await page.pdf({format: 'A4'})
  expect(pdf.subarray(0, 4).toString()).toBe('%PDF')
})

for (const width of [390, 768, 1440]) {
  test('экраны без горизонтальной прокрутки ' + width + ' px @screen', async ({page}) => {
    await page.setViewportSize({width, height: width === 390 ? 844 : 1000})
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    for (const route of ['analysis', 'compare', 'diary', 'diary/new', 'history', 'report', 'sources']) {
      await page.goto('./#/' + route)
      await expect(page.locator('h1')).toBeVisible()
      await page.evaluate(() => document.fonts.ready)
      await noOverflow(page)
      if (process.env.CAPTURE_SCREENSHOTS === '1' && width !== 768 && ['analysis', 'compare'].includes(route)) {
        await page.screenshot({path: 'docs/screenshots/' + route + '-' + width + '.png', fullPage: true, animations: 'disabled'})
      }
    }
    expect(errors).toEqual([])
  })
}
